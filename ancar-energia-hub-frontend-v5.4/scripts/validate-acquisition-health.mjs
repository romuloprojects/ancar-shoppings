import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
let fails=0; const ok=(c,m)=>{if(c) console.log(`PASS — ${m}`); else {fails++; console.error(`FAIL — ${m}`)}};
const svc=read('src/services/liveDashboardService.ts');
const top=read('src/components/TopBar.tsx');
const types=read('src/types/live.ts');
ok(types.includes('LiveValueFreshness'),'contrato de freshness por KPI');
ok(svc.includes('Math.max(10, (item.collectionIntervalMinutes ?? 3) * 3)'),'janela técnica mínima de 10 min');
ok(svc.includes('hasCriticalValueExpired'),'detecção de KPI crítico expirado');
ok(svc.includes('hasFallbackValue'),'detecção de fallback ativo');
ok(svc.includes('Sistema com atenção'),'estado amarelo de atenção');
ok(svc.includes('Comunicação degradada'),'estado vermelho de comunicação');
ok(top.includes('.getPortfolio()'),'TopBar lê o portfólio bruto para avaliar aquisição');
ok(top.includes('getPortfolioSystemStatus'),'TopBar usa saúde real da aquisição');
ok(top.includes('api-error') && top.includes('API indisponível'),'falha de API tem estado próprio');
ok(!top.includes('shoppings.length ? "Sistema Operacional" : "API indisponível"'),'regra antiga simplista removida');
console.log(`\n${10-fails} PASS / ${fails} FAIL — saúde de aquisição V5.0`);
if(fails) process.exit(1);
